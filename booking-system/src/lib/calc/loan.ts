export type LoanInput = {
  總價: number;
  自備款率: number;
  利率: number;
  年期: number;
  /** 只繳利息的年數，0 = 沒有寬限期 */
  寬限期年?: number;
  /** 買方仲介服務費率，預設 2% */
  買方服務費率?: number;
  /** 代書費、登記規費、印花稅概估（萬） */
  代書費?: number;
};

export function computeLoan(p: LoanInput) {
  const 自備款 = round(p.總價 * p.自備款率, 1);
  const 貸款額 = round(p.總價 - 自備款, 1);
  const 寬限期年 = p.寬限期年 ?? 0;

  // 寬限期只繳息，期滿後用剩下的年數重算本息攤還 —— 月付會跳一階，要讓客戶看到
  const 寬限期月付 = round((貸款額 * 10000 * p.利率) / 12);
  const 寬限後年期 = Math.max(p.年期 - 寬限期年, 1);
  const 月付 = round(monthlyPayment(貸款額, p.利率, 寬限期年 > 0 ? 寬限後年期 : p.年期));

  const 總繳 = 寬限期月付 * 12 * 寬限期年 + 月付 * 12 * 寬限後年期;
  const 總利息 = round(總繳 - 貸款額 * 10000);

  // 利率敏感度：升息 0.5% 對月付的衝擊，買方最該先知道的一件事
  const 敏感度 = [-0.005, 0, 0.005, 0.01].map((d) => {
    const r = Math.max(p.利率 + d, 0);
    const m = round(monthlyPayment(貸款額, r, 寬限期年 > 0 ? 寬限後年期 : p.年期));
    return { 利率: round(r * 100, 2), 月付: m, 差額: m - 月付 };
  });

  const 仲介服務費 = round(p.總價 * (p.買方服務費率 ?? 服務費率預設.買方), 1);
  const 代書費 = p.代書費 ?? 2;
  const 進場資金 = round(自備款 + 仲介服務費 + 代書費, 1);

  return {
    自備款,
    貸款額,
    月付,
    寬限期月付,
    寬限期年,
    寬限後年期,
    總利息,
    總繳: round(總繳),
    敏感度,
    仲介服務費,
    代書費,
    進場資金,
    /** 銀行常用門檻：月付不要超過月收入的 1/3 */
    建議月收入: round(月付 * 3),
  };
}
